"""Desk check of the settings table: runs the firmware self-check (src/settings_selftest.inc, the code behind USB
"cfgselftest") on the PC, with ArduinoJson from the PlatformIO library folder and MSVC.

It cuts the settings parts out of src/usb_msc_fat.cpp as they are (no copy by hand), adds small shims (Arduino
String, NVS, the watchdog) and prints the same CFGTEST lines as the board. Flash, FAT and USB are not in it.

Usage (from the repository root, Windows, Visual Studio Build Tools installed):
    python test/settings_host/run.py [--newkey]
Exit code: 0 with no difference, 1 with differences, 2 with a build error.
"""
import glob
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(HERE, 'build')


def cut(text, start, end, include_end=False):
    a = text.index(start)
    b = text.index(end, a)
    return text[a:b + (len(end) if include_end else 0)]


# --newkey: the one new table line (test_new_setting) through list, get, set, config.json and NVS
NEWKEY_MAIN = r'''
int main() {
    static DeviceConfig c, d;
    new_defaults(c);
    String line, v;
    int n = 0;
    for (; msc_fat_key_at(&c, n, &line); n++)
        if (line.startsWith("radio_mode") || line.startsWith("test_new_setting") || line.startsWith("dsp_frame_period_us_eff"))
            printf("NEWKEY list %d %s\n", n, line.c_str());
    printf("NEWKEY list keys %d\n", n);
    msc_fat_get_key(&c, "test_new_setting", &v);
    printf("NEWKEY get test_new_setting=%s\n", v.c_str());
    String why;
    int r = msc_fat_set_key(&c, "test_new_setting", "42", &why);
    msc_fat_get_key(&c, "test_new_setting", &v);
    printf("NEWKEY set 42: answer %d, get %s\n", r, v.c_str());
    r = msc_fat_set_key(&c, "test_new_setting", "101", &why);
    msc_fat_get_key(&c, "test_new_setting", &v);
    printf("NEWKEY set 101: answer %d (%s), get %s\n", r, why.c_str(), v.c_str());
    {
        JsonDocument doc;
        config_to_doc(c, doc);
        String s;
        serializeJson(doc, s);
        printf("NEWKEY config.json has it: %s\n", strstr(s.c_str(), "\"test_new_setting\":42") ? "yes" : "no");
    }
    new_defaults(d);
    config_from_json_text(d, "{\"test_new_setting\":55}");
    settings_check(d, SRC_JSON);
    printf("NEWKEY config.json read 55: %d\n", d.test_new_setting);
    new_defaults(d);
    config_from_json_text(d, "{\"test_new_setting\":500}");
    settings_check(d, SRC_JSON);
    char bad[96]; int src;
    while (msc_fat_bad_value_pop(bad, sizeof(bad), &src)) printf("NEWKEY SETTING bad value %s\n", bad);
    printf("NEWKEY config.json read 500: %d\n", d.test_new_setting);
    RamPrefs rp;
    prefs_save_to(rp, c);
    new_defaults(d);
    prefs_load_from(rp, d);
    printf("NEWKEY nvs round trip: %d (NVS key testNew %s)\n", d.test_new_setting, rp.find("testNew") ? "stored" : "missing");
    RamPrefs old;  // an NVS image of 0.5.111: no testNew key
    old_prefs_save(old, c);
    new_defaults(d);
    prefs_load_from(old, d);
    printf("NEWKEY load of a 0.5.111 image: %d (the default)\n", d.test_new_setting);
    return 0;
}
'''


def main():
    newkey = '--newkey' in sys.argv
    src = open(os.path.join(ROOT, 'src', 'usb_msc_fat.cpp'), encoding='utf-8').read().replace('\r\n', '\n')
    parts = [
        cut(src, '// Settings table (include/settings_table.h)', '// Flash block device'),
        cut(src, 'double g_dsp_eff[DSP_EFF_N]', 'static bool config_write_json('),
        'static bool s_rate_config_missing = false;\n',
        cut(src, '// One value for one table key', '// Config file change detection helpers'),
        cut(src, 'bool msc_fat_get_key(', '// Erase (USB and CMD'),
    ]
    tu = ['// Generated by test/settings_host/run.py from src/usb_msc_fat.cpp: do not edit',
          '#define SETTINGS_SELFTEST 1',
          '#include <Arduino.h>',
          '#include "decimator.h"',
          '#include "usb_msc_fat.h"',
          '#include <ArduinoJson.h>',
          '#include <math.h>', '#include <stddef.h>', '#include <type_traits>', '#include <utility>',
          '#include "nvs.h"',
          'static const char* TAG = "msc_fat";',
          '#define NVS_NAMESPACE "wfrx_cfg"',
          '#define PWM_ABS_MIN 800', '#define PWM_ABS_MAX 2200',
          'const char* msc_fat_wifi_ssid() { return ""; }',
          'bool msc_fat_wifi_has_password() { return false; }',
          'static uint32_t s_ms = 0; uint32_t millis() { return s_ms += 1; }',
          ] + parts + [
          '#include "settings_selftest.inc"',
          NEWKEY_MAIN if newkey else
          'int main() { const int d = msc_fat_selftest([](const char* s) { printf("CFGTEST %s\\n", s); }); return d ? 1 : 0; }',
          '']
    os.makedirs(BUILD, exist_ok=True)
    tu_path = os.path.join(BUILD, 'settings_tu.cpp')
    open(tu_path, 'w', encoding='utf-8').write('\n'.join(tu))

    vswhere = r'C:\Program Files (x86)\Microsoft Visual Studio\Installer\vswhere.exe'
    vs = subprocess.run([vswhere, '-latest', '-products', '*', '-property', 'installationPath'],
                        capture_output=True, text=True).stdout.strip()
    vcvars = os.path.join(vs, 'VC', 'Auxiliary', 'Build', 'vcvars64.bat')
    ajson = glob.glob(os.path.join(ROOT, '.pio', 'libdeps', '*', 'ArduinoJson', 'src'))[0]
    incs = [os.path.join(HERE, 'shim'), os.path.join(ROOT, 'include'), os.path.join(ROOT, 'src'),
            os.path.join(ROOT, 'lib', 'rover_telemetry'), ajson]
    defs = ['ARDUINOJSON_ENABLE_ARDUINO_STRING=1', 'ARDUINOJSON_ENABLE_STD_STRING=0', 'ARDUINOJSON_ENABLE_STD_STREAM=0']
    if newkey:
        defs.append('SETTINGS_NEWKEY')
    exe = os.path.join(BUILD, 'settings_test.exe')
    cl = ('cl /nologo /std:c++17 /EHsc /O1 /W3 /wd4244 /wd4267 /wd4996 /wd4305 '
          + ' '.join(f'/I"{i}"' for i in incs) + ' ' + ' '.join(f'/D{d}' for d in defs)
          + f' /Fo"{BUILD}\\\\" /Fe"{exe}" "{tu_path}" "{os.path.join(ROOT, "lib", "rover_telemetry", "decimator.cpp")}"')
    bat = os.path.join(BUILD, 'build.bat')
    open(bat, 'w').write(f'@call "{vcvars}" >nul\r\n{cl}\r\n')
    r = subprocess.run(['cmd', '/c', bat], capture_output=True, text=True)
    if r.returncode:
        print(r.stdout[-6000:], r.stderr[-3000:])
        return 2
    r = subprocess.run([exe], capture_output=True, text=True)
    sys.stdout.write(r.stdout)
    return r.returncode


if __name__ == '__main__':
    sys.exit(main())
