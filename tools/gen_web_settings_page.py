"""Write src/web_settings_page_gz.h (the settings page of the ESP32, gzipped) from src/web_settings_page.html and the
words of docs/settings_def.json.

The page builds its form from GET /api/settings, which the firmware makes from the settings table at run time. The
table lines of the first step have no words (unit, group, label, help); for those keys the page takes the words from
the copy that this script puts in the page: the groups in user order, and per key its group, label, description,
unit, value list, "restart" and "remote". A key with words in its table line uses the table words.

Usage (repository root):
    python tools/gen_web_settings_page.py           write src/web_settings_page_gz.h
    python tools/gen_web_settings_page.py --check   exit 1 if the header is not the generated text
"""
import gzip
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
HTML = os.path.join(ROOT, 'src', 'web_settings_page.html')
DEF = os.path.join(ROOT, 'docs', 'settings_def.json')
OUT = os.path.join(ROOT, 'src', 'web_settings_page_gz.h')
MARK = '/*WORDS*/null'


def words():
    d = json.load(open(DEF, encoding='utf-8'))
    groups = [[g['name'], 1 if g.get('advanced') else 0, g.get('description', '')] for g in d['groups']]
    keys = {}
    for k, s in d['settings'].items():
        if s.get('readonly'):
            continue  # values in effect and Wi-Fi details: not settings of the table
        w = {'g': s.get('group', ''), 'l': s.get('label', ''), 'h': s.get('description', '')}
        if s.get('unit'):
            w['u'] = s['unit']
        vals = s.get('values') or s.get('choices')
        if vals and s.get('type') in ('int', 'float'):
            w['vals'] = vals  # a number from a list: a drop-down
        if s.get('restart'):
            w['restart'] = 1
        if s.get('remote') is False:
            w['remote'] = 0
        keys[k] = w
    return {'version': d.get('version'), 'groups': groups, 'keys': keys}


def generate():
    html = open(HTML, encoding='utf-8').read().replace('\r\n', '\n')
    if html.count(MARK) != 1:
        sys.exit(f'{HTML}: the mark {MARK} must occur once')
    blob = json.dumps(words(), ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
    page = html.replace(MARK, blob).encode('utf-8')
    gz = gzip.compress(page, compresslevel=9, mtime=0)
    rows = [', '.join(f'0x{b:02x}' for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
    text = ('// Generated by tools/gen_web_settings_page.py from src/web_settings_page.html and docs/settings_def.json:\n'
            '// do not edit. Page %d B, gzipped %d B.\n'
            '#pragma once\n#include <stdint.h>\n\n'
            'static const uint8_t WEB_SETTINGS_PAGE_GZ[] = {\n  %s\n};\n') % (len(page), len(gz), ',\n  '.join(rows))
    return text, len(page), len(gz)


def main():
    text, n_page, n_gz = generate()
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read().replace('\r\n', '\n') if os.path.exists(OUT) else ''
        if cur != text:
            print(f'{OUT} differs: run python tools/gen_web_settings_page.py', file=sys.stderr)
            return 1
        print(f'{OUT}: as generated')
        return 0
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'{OUT}: written, page {n_page} B, gzipped {n_gz} B')
    return 0


if __name__ == '__main__':
    sys.exit(main())
