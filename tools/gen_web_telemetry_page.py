"""Write src/web_telemetry_page_gz.h (the telemetry page of the ESP32, gzipped) from src/web_telemetry_page.html.

The page holds no field list: it reads the fields, labels, units and groups from GET /api/telemetry?def=1, which the
firmware makes from the telemetry table at run time (lib/tlm_page).

Usage (repository root):
    python tools/gen_web_telemetry_page.py           write src/web_telemetry_page_gz.h
    python tools/gen_web_telemetry_page.py --check   exit 1 if the header is not the generated text
"""
import gzip
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
HTML = os.path.join(ROOT, 'src', 'web_telemetry_page.html')
OUT = os.path.join(ROOT, 'src', 'web_telemetry_page_gz.h')


def generate():
    page = open(HTML, encoding='utf-8').read().replace('\r\n', '\n').encode('utf-8')
    gz = gzip.compress(page, compresslevel=9, mtime=0)
    rows = [', '.join(f'0x{b:02x}' for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
    text = ('// Generated by tools/gen_web_telemetry_page.py from src/web_telemetry_page.html: do not edit.\n'
            '// Page %d B, gzipped %d B.\n'
            '#pragma once\n#include <stdint.h>\n\n'
            'static const uint8_t WEB_TELEMETRY_PAGE_GZ[] = {\n  %s\n};\n') % (len(page), len(gz), ',\n  '.join(rows))
    return text, len(page), len(gz)


def main():
    text, n_page, n_gz = generate()
    if '--check' in sys.argv:
        cur = open(OUT, encoding='utf-8').read().replace('\r\n', '\n') if os.path.exists(OUT) else ''
        if cur != text:
            print(f'{OUT} differs: run python tools/gen_web_telemetry_page.py', file=sys.stderr)
            return 1
        print(f'{OUT}: as generated')
        return 0
    open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
    print(f'{OUT}: written, page {n_page} B, gzipped {n_gz} B')
    return 0


if __name__ == '__main__':
    sys.exit(main())
