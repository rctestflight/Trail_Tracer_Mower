"""PlatformIO extra script (after gen_telemetry_def_build.py): puts the definition files of this build into the image,
for "defget" (docs/espnow_protocol.md, "Definition files"). Writes <build folder>/settings_def.json (the settings table
with the build's -D SETTINGS_* flags) and <build folder>/def_files_gz.h: the gzip (level 9, no name, no time stamp) of
<build folder>/telemetry_def.json and settings_def.json, their versions and the crc32 of each gzip. The same file gives
the same bytes in every build. The files are part of the image: no flash write at run time."""
import gzip
import json
import os
import re
import subprocess
import sys
import zlib

Import("env")  # noqa: F821 (PlatformIO SCons)

build = env.subst("$BUILD_DIR")  # noqa: F821
proj = env.subst("$PROJECT_DIR")  # noqa: F821
os.makedirs(build, exist_ok=True)
flags = re.findall(r"-D\s*(SETTINGS_\w+)", str(env.GetProjectOption("build_flags")))  # noqa: F821
set_path = os.path.join(build, "settings_def.json")
cmd = [sys.executable, os.path.join(proj, "tools", "gen_settings_def.py"), "--quiet", "-o", set_path]
for f in flags:
    cmd += ["-D", f]
if subprocess.run(cmd).returncode:
    env.Exit(1)  # noqa: F821
tlm_path = os.path.join(build, "telemetry_def.json")


def block(name, path):
    raw = open(path, "rb").read()
    version = json.loads(raw)["version"]
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    rows = [", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
    return (f"// {os.path.basename(path)}: {len(raw)} B, gzipped {len(gz)} B\n"
            f"static const uint8_t DEF_{name}_GZ[] = {{\n  " + ",\n  ".join(rows) + "\n};\n"
            f"static const char DEF_{name}_VERSION[] = \"{version}\";\n"
            f"static const uint32_t DEF_{name}_CRC32 = 0x{zlib.crc32(gz):08x}u;\n"), len(gz)


tlm, n_tlm = block("TLM", tlm_path)
st, n_set = block("SET", set_path)
text = ("// Generated by tools/gen_def_files_build.py from the build's telemetry_def.json and settings_def.json: do not "
        "edit.\n#pragma once\n#include <stdint.h>\n\n" + tlm + "\n" + st)
out = os.path.join(build, "def_files_gz.h")
if not os.path.exists(out) or open(out, encoding="utf-8").read() != text:  # unchanged: no rebuild
    open(out, "w", encoding="utf-8", newline="\n").write(text)
env.Append(CPPPATH=[build])  # noqa: F821
print(f"def files: telemetry {n_tlm} B, settings {n_set} B gzipped")
